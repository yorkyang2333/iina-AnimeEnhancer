from pathlib import Path
import hashlib
import json

base_dir = Path(__file__).resolve().parent
sources = sorted((base_dir / 'Anime4K/glsl').rglob('*.glsl'))
if not sources:
    raise RuntimeError('Missing Anime4K shaders. Run git submodule update --init --recursive.')
janai_dir = base_dir / 'AnimeJaNai/ports/mpv-glsl'
janai_sources = sorted((janai_dir / 'shaders').glob('*.glsl'))
if not janai_sources:
    raise RuntimeError('Missing AnimeJaNai shaders. Run git submodule update --init --recursive.')
sources.extend(janai_sources)
shaders_data = {}
for source in sources:
    if source.name in shaders_data:
        raise ValueError(f'Duplicate shader filename: {source.name}')
    shaders_data[source.name] = source.read_text(encoding='utf-8')
serialized = json.dumps(shaders_data, sort_keys=True)
version = hashlib.sha256(serialized.encode()).hexdigest()
(base_dir / 'src/shaders-data.js').write_text(
    '// Generated by build-shaders.py\n'
    f'export const shadersVersion = {json.dumps(version)};\n'
    f'export const shadersData = {serialized};\n', encoding='utf-8')
print(f'Bundled {len(shaders_data)} shader files.')
