const { cpSync, mkdirSync, rmSync } = require("node:fs");
const { spawnSync } = require("node:child_process");
const { join } = require("node:path");
process.chdir(join(__dirname, ".."));
const dir = "animeenhancer.iinaplugin";
rmSync(dir, { recursive: true, force: true });
rmSync("animeenhancer.iinaplgz", { force: true });
mkdirSync(dir);
for (const path of ["dist", "Info.json", "package.json", "pref.html", "LICENSE", "THIRD_PARTY.md"]) cpSync(path, join(dir, path), { recursive: true });
mkdirSync(join(dir, "licenses"));
cpSync("Anime4K/LICENSE", join(dir, "licenses/Anime4K-MIT.txt"));
cpSync("AnimeJaNai/ports/mpv-glsl/models/animejanai/UPSTREAM-LICENSE", join(dir, "licenses/AnimeJaNai-CC-BY-NC-SA-4.0.txt"));
cpSync("AnimeJaNai/ports/mpv-glsl/models/animejanai/model.json", join(dir, "licenses/AnimeJaNai-model.json"));
cpSync("AnimeJaNai/ports/mpv-glsl/models/animejanai/super-ultra-compact.json", join(dir, "licenses/AnimeJaNai-super-ultra-compact.json"));
cpSync("AnimeJaNai/ports/mpv-glsl/models/animejanai/balanced.json", join(dir, "licenses/AnimeJaNai-balanced.json"));
cpSync("AnimeJaNai/ports/mpv-glsl/models/animejanai/sharp.json", join(dir, "licenses/AnimeJaNai-sharp.json"));
const result = spawnSync("zip", ["-qr", "../animeenhancer.iinaplgz", "."], { cwd: dir, stdio: "inherit" });
if (result.error) throw result.error;
process.exit(result.status || 0);
