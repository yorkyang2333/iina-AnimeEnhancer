let currentLocale = "en";

export function normalizeLang(lang) {
  if (!lang || typeof lang !== "string") return "en";
  const clean = lang.replace(/_/g, "-");

  if (supportedLocales.includes(clean)) return clean;

  const lower = clean.toLowerCase();
  if (lower.startsWith("zh-hans") || lower.includes("-cn") || lower.includes("-sg") || lower.includes("-my")) {
    return "zh-Hans";
  }
  if (lower.startsWith("zh-hant") || lower.includes("-tw") || lower.includes("-hk") || lower.includes("-mo")) {
    return "zh-Hant";
  }
  if (lower === "zh") return "zh-Hans";

  if (lower.startsWith("sr")) {
    if (lower.includes("latn") || lower.includes("latin")) return "sr-Latn";
    return "sr";
  }

  if (lower.startsWith("pt")) {
    if (lower.includes("br")) return "pt-BR";
    return "pt";
  }

  if (lower === "en-gb" || lower === "en-au" || lower === "en-nz") return "en-GB";

  const base = clean.split("-")[0].toLowerCase();
  if (supportedLocales.includes(base)) return base;

  return "en";
}

export function detectSystemLocale() {
  if (typeof navigator !== "undefined") {
    if (navigator.language) return normalizeLang(navigator.language);
    if (navigator.languages && navigator.languages.length > 0) return normalizeLang(navigator.languages[0]);
  }
  if (typeof Intl !== "undefined" && Intl.DateTimeFormat) {
    try {
      const loc = Intl.DateTimeFormat().resolvedOptions().locale;
      if (loc) return normalizeLang(loc);
    } catch (e) {}
  }
  if (typeof process !== "undefined" && process.env) {
    const envLang = process.env.LC_ALL || process.env.LC_MESSAGES || process.env.LANG;
    if (envLang) {
      return normalizeLang(envLang.split(".")[0]);
    }
  }
  return "en";
}

export function setLocale(lang) {
  if (lang && lang !== "auto") {
    currentLocale = normalizeLang(lang);
  } else {
    currentLocale = detectSystemLocale();
  }
  return currentLocale;
}

export function getLocale() {
  return currentLocale;
}

export function t(key, params = {}) {
  const dict = translations[currentLocale] || translations["en"];
  let text = dict[key] || translations["en"][key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, "g"), v);
  }
  return text;
}

